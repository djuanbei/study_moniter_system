def sync_knowledge_points(db: Session) -> int:
    """Create KnowledgePoint rows from chapter.knowledge_points JSON lists.

    Idempotent: matches on (name, textbook_version, grade). Returns the
    number of newly created rows.
    """
    created = 0
    chapters = db.query(Chapter).all()
    for ch in chapters:
        for name in ch.knowledge_points or []:
            if not name or not str(name).strip():
                continue
            name = str(name).strip()
            exists = (
                db.query(KnowledgePoint)
                .filter(
                    KnowledgePoint.name == name,
                    KnowledgePoint.textbook_version == ch.textbook_version,
                    KnowledgePoint.grade == ch.grade,
                )
                .first()
            )
            if exists:
                if exists.chapter_id is None:
                    exists.chapter_id = ch.id
                continue
            db.add(
                KnowledgePoint(
                    subject="math",
                    name=name,
                    chapter_id=ch.id,
                    grade=ch.grade,
                    textbook_version=ch.textbook_version,
                )
            )
            created += 1
    db.flush()
    return created


def get_or_create_knowledge_point(
    db: Session,
    name: str,
    *,
    grade: Optional[str] = None,
    textbook_version: Optional[str] = None,
    chapter_id: Optional[int] = None,
) -> KnowledgePoint:
    name = (name or "").strip()
    kp = (
        db.query(KnowledgePoint)
        .filter(KnowledgePoint.name == name)
        .order_by(KnowledgePoint.id.asc())
        .first()
    )
    if kp:
        return kp
    kp = KnowledgePoint(
        name=name, grade=grade, textbook_version=textbook_version, chapter_id=chapter_id
    )
    db.add(kp)
    db.flush()
    return kp


