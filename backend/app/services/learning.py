"""Learning-loop services.

Implements the PRD core loop (§7, §59, §29, §30):
    Learning Evidence -> Student Knowledge State update -> Diagnosis -> Learning Plan

State update model (PRD §59) — an evidence-weighted exponential moving average:
    new = old + lr * (observation - old)
where the learning rate is modulated by question difficulty, evidence trust
level and error type (careless mistakes move mastery far less than real
misunderstandings).

Diagnosis (PRD §29) is deterministic: low mastery, declining trend and decay
risk are combined into a priority ranking. The learning plan (PRD §30–31) is
generated by the LLM when available with this same heuristic as fallback.
"""

from __future__ import annotations

import logging
import math
from datetime import datetime
from typing import Any, Optional

from sqlalchemy.orm import Session

from app.models.assignments import Assignment, Grading, Question, QuestionSet, Submission
from app.models.learning import (
    ERROR_PATTERNS,
    INTERVENTION_TYPES,
    KnowledgePoint,
    LearningEvidence,
    LearningPlan,
    LearningPlanItem,
    StudentKnowledgeState,
    StudentKnowledgeStateHistory,
)
from app.models.students import Chapter, Student

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Tuning constants (PRD §57, §59, §60, §61)
# ---------------------------------------------------------------------------

BASE_LEARNING_RATE = 0.25  # max share of the gap closed by one evidence
DIFFICULTY_WEIGHT = {"easy": 0.85, "medium": 1.0, "hard": 1.15}
TRUST_WEIGHT = {
    "RAW": 0.5,
    "AI_EXTRACTED": 0.7,
    "VALIDATED": 0.85,
    "PARENT_CONFIRMED": 1.0,  # official evidence boundary (PRD §57)
    "OFFICIAL": 1.0,
}
# Careless mistakes say little about knowledge; concept errors say a lot.
ERROR_WEIGHT = {
    "CARELESS_ERROR": 0.45,
    "READING_ERROR": 0.6,
    "CALCULATION_ERROR": 0.75,
    "SIGN_ERROR": 0.8,
    "DIAGRAM_ERROR": 0.85,
}
PASS_THRESHOLD = 60.0  # per-question score (0–100) counted as "correct"

# Spaced review intervals in days by mastery band (PRD §61).
REVIEW_INTERVALS = ((0.4, 1), (0.6, 3), (0.8, 7), (0.9, 14), (1.01, 30))
DECAY_BANDS = ((7, "LOW"), (30, "MEDIUM"), (90, "HIGH"), (float("inf"), "CRITICAL"))

OPEN_ENDED_QTYPES = {"composition", "reading_comprehension"}  # always parent-reviewed
AUTO_CONFIRM_CONFIDENCE = 0.80  # PRD §47–48: below this → needs parent review


